import AppKit
import CryptoKit
import Observation

struct ClipEntry: Codable, Identifiable, Equatable {
    var id = UUID()
    var text: String?
    var imageFile: String?
    var date = Date()
    var isPinned = false
}

/// Remembers what is copied on this Mac. It is stored only in this user's Application Support folder.
/// Anything an app marks as private or temporary, such as password manager content, is never recorded.
@MainActor
@Observable
final class ClipboardHistory {
    private(set) var entries: [ClipEntry] = []
    var ignoresPasswords: Bool {
        didSet { defaults.set(ignoresPasswords, forKey: "clipboard.ignorePasswords") }
    }
    /// Pinned entries don't count toward either limit.
    private(set) var maxEntries: Int
    private(set) var maxImages: Int

    static let entryChoices = [50, 100, 200, 500, 1000]
    static let imageChoices = [10, 30, 60, 100]
    static let defaultEntries = 200
    static let defaultImages = 30
    private static let maxTextBytes = 1_048_576
    private static let maxImageBytes = 20_000_000
    private static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ]

    @ObservationIgnored private let directory: URL
    @ObservationIgnored private let defaults: UserDefaults
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastChange = NSPasteboard.general.changeCount
    @ObservationIgnored private var pendingSave: DispatchWorkItem?
    @ObservationIgnored private var thumbnails: [String: NSImage] = [:]

    private var storeFile: URL { directory.appendingPathComponent("clipboard-history.json") }

    init(directory: URL, defaults: UserDefaults = .standard) {
        self.directory = directory
        self.defaults = defaults
        ignoresPasswords = defaults.object(forKey: "clipboard.ignorePasswords") as? Bool ?? true
        let entries = defaults.integer(forKey: "clipboard.maxEntries")
        let images = defaults.integer(forKey: "clipboard.maxImages")
        maxEntries = Self.entryChoices.contains(entries) ? entries : Self.defaultEntries
        maxImages = Self.imageChoices.contains(images) ? images : Self.defaultImages
        load()
    }

    /// How many saved entries new limits would remove, so lowering them can be confirmed first.
    func removedCount(maxEntries: Int, maxImages: Int) -> Int {
        Self.trimmed(entries, maxEntries: maxEntries, maxImages: maxImages).removed.count
    }

    /// Removes the oldest unpinned entries that no longer fit.
    func setLimits(maxEntries: Int, maxImages: Int) {
        guard Self.entryChoices.contains(maxEntries), Self.imageChoices.contains(maxImages) else { return }
        self.maxEntries = maxEntries
        self.maxImages = maxImages
        defaults.set(maxEntries, forKey: "clipboard.maxEntries")
        defaults.set(maxImages, forKey: "clipboard.maxImages")
        trimAndSave()
    }

    func start() {
        guard timer == nil else { return }
        // What was copied while this was off stays unrecorded.
        lastChange = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated {
                guard let self else { return }
                let board = NSPasteboard.general
                guard board.changeCount != self.lastChange else { return }
                self.lastChange = board.changeCount
                self.capture(from: board, frontApp: NSWorkspace.shared.frontmostApplication?.bundleIdentifier)
            }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func capture(from board: NSPasteboard, frontApp: String? = nil) {
        let types = (board.types ?? []).map(\.rawValue)
        if types.contains(where: Self.skippedTypes.contains) { return }
        if ignoresPasswords, let frontApp, PasswordFilter.passwordApps.contains(frontApp) { return }
        if let text = board.string(forType: .string) {
            if ignoresPasswords, PasswordFilter.looksLikePassword(text) { return }
            add(text: text)
        } else if let image = Self.pngData(from: board) {
            add(image: image)
        }
    }

    func add(text: String) {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              text.utf8.count <= Self.maxTextBytes
        else { return }
        var entry = ClipEntry(text: text)
        if let index = entries.firstIndex(where: { $0.text == text }) {
            entry.isPinned = entries.remove(at: index).isPinned
        }
        entries.insert(entry, at: 0)
        trimAndSave()
    }

    func add(image data: Data) {
        guard data.count <= Self.maxImageBytes else { return }
        let hash = SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
        let name = hash + ".png"
        var entry = ClipEntry(imageFile: name)
        if let index = entries.firstIndex(where: { $0.imageFile == name }) {
            entry.isPinned = entries.remove(at: index).isPinned
        } else {
            prepareDirectory()
            let file = imageURL(name)
            guard (try? data.write(to: file, options: .atomic)) != nil else { return }
            try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: file.path)
        }
        entries.insert(entry, at: 0)
        trimAndSave()
    }

    func matches(_ query: String) -> [ClipEntry] {
        let words = query.trimmingCharacters(in: .whitespaces)
        let found = words.isEmpty ? entries : entries.filter { $0.text?.localizedCaseInsensitiveContains(words) == true }
        return found.filter(\.isPinned) + found.filter { !$0.isPinned }
    }

    /// Puts the entry back on the clipboard and moves it to the top.
    func copy(_ entry: ClipEntry) {
        let board = NSPasteboard.general
        board.clearContents()
        if let text = entry.text {
            board.setString(text, forType: .string)
            lastChange = board.changeCount
            add(text: text)
        } else if let name = entry.imageFile, let data = try? Data(contentsOf: imageURL(name)) {
            board.setData(data, forType: .png)
            lastChange = board.changeCount
            add(image: data)
        }
    }

    /// For text from a screen capture. It goes on the clipboard and into the history.
    func copy(text: String) {
        let board = NSPasteboard.general
        board.clearContents()
        board.setString(text, forType: .string)
        lastChange = board.changeCount
        add(text: text)
    }

    func togglePin(_ entry: ClipEntry) {
        guard let index = entries.firstIndex(where: { $0.id == entry.id }) else { return }
        entries[index].isPinned.toggle()
        scheduleSave()
    }

    func delete(_ entry: ClipEntry) {
        entries.removeAll { $0.id == entry.id }
        removeImage(of: entry)
        scheduleSave()
    }

    /// Pinned entries stay.
    func clearUnpinned() {
        let removed = entries.filter { !$0.isPinned }
        entries.removeAll { !$0.isPinned }
        removed.forEach(removeImage)
        saveNow()
    }

    var unpinnedCount: Int { entries.filter { !$0.isPinned }.count }

    /// Saved items that look like passwords, for removing what was recorded before this was on.
    var passwordLikeCount: Int { entries.filter { $0.text.map(PasswordFilter.looksLikePassword) == true }.count }

    func removePasswordLike() {
        entries.removeAll { $0.text.map(PasswordFilter.looksLikePassword) == true }
        saveNow()
    }

    func imageURL(_ name: String) -> URL {
        directory.appendingPathComponent("clipboard-images", isDirectory: true).appendingPathComponent(name)
    }

    func thumbnail(_ name: String) -> NSImage? {
        if let cached = thumbnails[name] { return cached }
        let image = NSImage(contentsOf: imageURL(name))
        thumbnails[name] = image
        return image
    }

    private func trimAndSave() {
        let result = Self.trimmed(entries, maxEntries: maxEntries, maxImages: maxImages)
        result.removed.forEach(removeImage)
        entries = result.kept
        scheduleSave()
    }

    /// Entries are newest first, so the oldest unpinned ones are removed.
    static func trimmed(_ entries: [ClipEntry], maxEntries: Int, maxImages: Int) -> (kept: [ClipEntry], removed: [ClipEntry]) {
        var images = 0
        var total = 0
        var kept: [ClipEntry] = []
        var removed: [ClipEntry] = []
        for entry in entries {
            if entry.isPinned {
                kept.append(entry)
                continue
            }
            let isImage = entry.imageFile != nil
            if total >= maxEntries || (isImage && images >= maxImages) {
                removed.append(entry)
                continue
            }
            total += 1
            if isImage { images += 1 }
            kept.append(entry)
        }
        return (kept, removed)
    }

    private func removeImage(of entry: ClipEntry) {
        guard let name = entry.imageFile else { return }
        thumbnails[name] = nil
        try? FileManager.default.removeItem(at: imageURL(name))
    }

    private func scheduleSave() {
        pendingSave?.cancel()
        let work = DispatchWorkItem { [weak self] in
            MainActor.assumeIsolated { self?.saveNow() }
        }
        pendingSave = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 1, execute: work)
    }

    func saveNow() {
        pendingSave?.cancel()
        pendingSave = nil
        prepareDirectory()
        guard let data = try? JSONEncoder().encode(entries),
              (try? data.write(to: storeFile, options: .atomic)) != nil
        else { return }
        try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: storeFile.path)
    }

    private func load() {
        guard let data = try? Data(contentsOf: storeFile),
              let saved = try? JSONDecoder().decode([ClipEntry].self, from: data)
        else { return }
        entries = saved
    }

    private func prepareDirectory() {
        let manager = FileManager.default
        let images = directory.appendingPathComponent("clipboard-images", isDirectory: true)
        try? manager.createDirectory(at: images, withIntermediateDirectories: true)
        for folder in [directory, images] {
            try? manager.setAttributes([.posixPermissions: 0o700], ofItemAtPath: folder.path)
        }
        var root = directory
        var values = URLResourceValues()
        values.isExcludedFromBackup = true
        try? root.setResourceValues(values)
    }

    private static func pngData(from board: NSPasteboard) -> Data? {
        if let png = board.data(forType: .png) { return png }
        guard let tiff = board.data(forType: .tiff), let image = NSBitmapImageRep(data: tiff) else { return nil }
        return image.representation(using: .png, properties: [:])
    }
}
