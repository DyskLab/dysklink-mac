import AppKit
import CryptoKit
import ImageIO
import Observation

struct ClipEntry: Codable, Identifiable, Equatable, Sendable {
    var id = UUID()
    var text: String?
    var imageFile: String?
    var date = Date()
    var isPinned = false
}

/// Remembers what is copied on this Mac. It is stored only in this user's Application Support folder.
/// Anything an app marks as private or temporary, such as password manager content, is never recorded.
@MainActor
@Observable
final class ClipboardHistory {
    private(set) var entries: [ClipEntry] = []
    var ignoresPasswords: Bool {
        didSet { defaults.set(ignoresPasswords, forKey: "clipboard.ignorePasswords") }
    }
    /// Pinned entries don't count toward either limit.
    private(set) var maxEntries: Int
    private(set) var maxImages: Int

    /// 0 means no limit.
    static let unlimited = 0
    static let entryChoices = [50, 100, 200, 500, 1000, 5000, unlimited]
    static let imageChoices = [10, 30, 60, 100, 500, unlimited]
    static let defaultEntries = 200
    static let defaultImages = 30
    private static let maxTextBytes = 1_048_576
    nonisolated private static let maxImageBytes = 20_000_000
    private static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ]

    @ObservationIgnored private let directory: URL
    @ObservationIgnored private let defaults: UserDefaults
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastChange = NSPasteboard.general.changeCount
    @ObservationIgnored private var pendingSave: DispatchWorkItem?
    /// Small copies of the images for the lists, a bounded number kept in memory.
    @ObservationIgnored private let thumbnails: NSCache<NSString, NSImage> = {
        let cache = NSCache<NSString, NSImage>()
        cache.countLimit = 60
        return cache
    }()
    /// Saves run here in order, so a long history doesn't stall typing in the panel.
    private static let saveQueue = DispatchQueue(label: "id.dysklink.clipboard.save", qos: .utility)
    /// Copied images are converted, hashed, and written here, off the main thread.
    private static let imageQueue = DispatchQueue(label: "id.dysklink.clipboard.images", qos: .utility)
    nonisolated static let thumbnailPixels = 200

    private var storeFile: URL { directory.appendingPathComponent("clipboard-history.json") }

    init(directory: URL, defaults: UserDefaults = .standard) {
        self.directory = directory
        self.defaults = defaults
        ignoresPasswords = defaults.object(forKey: "clipboard.ignorePasswords") as? Bool ?? true
        // A missing setting must not read as 0, which means no limit.
        let entries = defaults.object(forKey: "clipboard.maxEntries") as? Int
        let images = defaults.object(forKey: "clipboard.maxImages") as? Int
        maxEntries = entries.flatMap { Self.entryChoices.contains($0) ? $0 : nil } ?? Self.defaultEntries
        maxImages = images.flatMap { Self.imageChoices.contains($0) ? $0 : nil } ?? Self.defaultImages
        load()
        undoSharedExclusion()
    }

    /// How many saved entries new limits would remove, so lowering them can be confirmed first.
    func removedCount(maxEntries: Int, maxImages: Int) -> Int {
        Self.trimmed(entries, maxEntries: maxEntries, maxImages: maxImages).removed.count
    }

    /// Removes the oldest unpinned entries that no longer fit.
    func setLimits(maxEntries: Int, maxImages: Int) {
        guard Self.entryChoices.contains(maxEntries), Self.imageChoices.contains(maxImages) else { return }
        self.maxEntries = maxEntries
        self.maxImages = maxImages
        defaults.set(maxEntries, forKey: "clipboard.maxEntries")
        defaults.set(maxImages, forKey: "clipboard.maxImages")
        trimAndSave()
    }

    func start() {
        guard timer == nil else { return }
        // What was copied while this was off stays unrecorded.
        lastChange = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated {
                guard let self else { return }
                let board = NSPasteboard.general
                guard board.changeCount != self.lastChange else { return }
                self.lastChange = board.changeCount
                self.capture(from: board, frontApp: NSWorkspace.shared.frontmostApplication?.bundleIdentifier)
            }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func capture(from board: NSPasteboard, frontApp: String? = nil) {
        let types = (board.types ?? []).map(\.rawValue)
        if types.contains(where: Self.skippedTypes.contains) { return }
        if ignoresPasswords, let frontApp, PasswordFilter.passwordApps.contains(frontApp) { return }
        if let text = board.string(forType: .string) {
            if ignoresPasswords, PasswordFilter.looksLikePassword(text) { return }
            add(text: text)
        } else if let raw = Self.imageData(from: board) {
            addInBackground(raw)
        }
    }

    /// Converts a copied image to PNG, hashes and saves it on a background queue, then adds it.
    private func addInBackground(_ raw: (data: Data, isPNG: Bool)) {
        let folder = imagesFolder
        Self.imageQueue.async {
            guard let data = raw.isPNG ? raw.data : Self.png(fromTIFF: raw.data), data.count <= Self.maxImageBytes else { return }
            let name = Self.imageName(data)
            let file = folder.appendingPathComponent(name)
            if !FileManager.default.fileExists(atPath: file.path) {
                try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
                guard (try? data.write(to: file, options: .atomic)) != nil else { return }
                try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: file.path)
            }
            let thumbnail = Self.makeThumbnail(file)
            DispatchQueue.main.async {
                MainActor.assumeIsolated {
                    if let thumbnail { self.thumbnails.setObject(thumbnail, forKey: name as NSString) }
                    self.prepareDirectory()
                    self.insertImage(name)
                }
            }
        }
    }

    nonisolated private static func imageName(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined() + ".png"
    }

    private func insertImage(_ name: String) {
        var entry = ClipEntry(imageFile: name)
        if let index = entries.firstIndex(where: { $0.imageFile == name }) {
            entry.isPinned = entries.remove(at: index).isPinned
        }
        entries.insert(entry, at: 0)
        trimAndSave()
    }

    func add(text: String) {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              text.utf8.count <= Self.maxTextBytes
        else { return }
        var entry = ClipEntry(text: text)
        if let index = entries.firstIndex(where: { $0.text == text }) {
            entry.isPinned = entries.remove(at: index).isPinned
        }
        entries.insert(entry, at: 0)
        trimAndSave()
    }

    /// Adds a PNG right away. Copies from the clipboard go through the background queue instead.
    func add(image data: Data) {
        guard data.count <= Self.maxImageBytes else { return }
        let name = Self.imageName(data)
        var entry = ClipEntry(imageFile: name)
        if let index = entries.firstIndex(where: { $0.imageFile == name }) {
            entry.isPinned = entries.remove(at: index).isPinned
        } else {
            prepareDirectory()
            let file = imageURL(name)
            guard (try? data.write(to: file, options: .atomic)) != nil else { return }
            try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: file.path)
        }
        entries.insert(entry, at: 0)
        trimAndSave()
    }

    func matches(_ query: String) -> [ClipEntry] {
        let words = query.trimmingCharacters(in: .whitespaces)
        let found = words.isEmpty ? entries : entries.filter { $0.text?.localizedCaseInsensitiveContains(words) == true }
        return found.filter(\.isPinned) + found.filter { !$0.isPinned }
    }

    /// Puts the entry back on the clipboard and moves it to the top.
    func copy(_ entry: ClipEntry) {
        let board = NSPasteboard.general
        board.clearContents()
        if let text = entry.text {
            board.setString(text, forType: .string)
            lastChange = board.changeCount
            add(text: text)
        } else if let name = entry.imageFile, let data = try? Data(contentsOf: imageURL(name)) {
            board.setData(data, forType: .png)
            lastChange = board.changeCount
            // The file is named by its hash already, so it only moves to the top.
            insertImage(name)
        }
    }

    /// For text from a screen capture. It goes on the clipboard and into the history.
    func copy(text: String) {
        let board = NSPasteboard.general
        board.clearContents()
        board.setString(text, forType: .string)
        lastChange = board.changeCount
        add(text: text)
    }

    func togglePin(_ entry: ClipEntry) {
        guard let index = entries.firstIndex(where: { $0.id == entry.id }) else { return }
        entries[index].isPinned.toggle()
        scheduleSave()
    }

    func delete(_ entry: ClipEntry) {
        entries.removeAll { $0.id == entry.id }
        removeImage(of: entry)
        scheduleSave()
    }

    /// Pinned entries stay.
    func clearUnpinned() {
        let removed = entries.filter { !$0.isPinned }
        entries.removeAll { !$0.isPinned }
        removed.forEach(removeImage)
        saveNow()
    }

    var unpinnedCount: Int { entries.filter { !$0.isPinned }.count }

    /// Saved items that look like passwords, for removing what was recorded before this was on.
    var passwordLikeCount: Int { entries.filter { $0.text.map(PasswordFilter.looksLikePassword) == true }.count }

    func removePasswordLike() {
        entries.removeAll { $0.text.map(PasswordFilter.looksLikePassword) == true }
        saveNow()
    }

    private var imagesFolder: URL { directory.appendingPathComponent("clipboard-images", isDirectory: true) }

    func imageURL(_ name: String) -> URL {
        imagesFolder.appendingPathComponent(name)
    }

    /// A copy about 200 pixels across, for the lists. The full image is only read when it's copied back.
    func thumbnail(_ name: String) -> NSImage? {
        if let cached = thumbnails.object(forKey: name as NSString) { return cached }
        guard let image = Self.makeThumbnail(imageURL(name)) else { return nil }
        thumbnails.setObject(image, forKey: name as NSString)
        return image
    }

    nonisolated static func makeThumbnail(_ file: URL) -> NSImage? {
        guard let source = CGImageSourceCreateWithURL(file as CFURL, nil) else { return nil }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: thumbnailPixels,
        ]
        guard let image = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return nil }
        return NSImage(cgImage: image, size: NSSize(width: image.width, height: image.height))
    }

    private func trimAndSave() {
        let result = Self.trimmed(entries, maxEntries: maxEntries, maxImages: maxImages)
        result.removed.forEach(removeImage)
        entries = result.kept
        scheduleSave()
    }

    /// Entries are newest first, so the oldest unpinned ones are removed.
    static func trimmed(_ entries: [ClipEntry], maxEntries: Int, maxImages: Int) -> (kept: [ClipEntry], removed: [ClipEntry]) {
        let maxEntries = maxEntries == unlimited ? Int.max : maxEntries
        let maxImages = maxImages == unlimited ? Int.max : maxImages
        var images = 0
        var total = 0
        var kept: [ClipEntry] = []
        var removed: [ClipEntry] = []
        for entry in entries {
            if entry.isPinned {
                kept.append(entry)
                continue
            }
            let isImage = entry.imageFile != nil
            if total >= maxEntries || (isImage && images >= maxImages) {
                removed.append(entry)
                continue
            }
            total += 1
            if isImage { images += 1 }
            kept.append(entry)
        }
        return (kept, removed)
    }

    private func removeImage(of entry: ClipEntry) {
        guard let name = entry.imageFile else { return }
        thumbnails.removeObject(forKey: name as NSString)
        try? FileManager.default.removeItem(at: imageURL(name))
    }

    private func scheduleSave() {
        pendingSave?.cancel()
        let work = DispatchWorkItem { [weak self] in
            MainActor.assumeIsolated {
                guard let self else { return }
                self.pendingSave = nil
                self.prepareDirectory()
                let entries = self.entries, file = self.storeFile
                Self.saveQueue.async { Self.write(entries, to: file) }
            }
        }
        pendingSave = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 1, execute: work)
    }

    /// Writes a save that's still waiting, for quitting. Nothing is written when nothing changed.
    func flush() {
        guard pendingSave != nil else { return }
        saveNow()
    }

    /// Waits for the write, for quitting and for actions that can't be undone.
    func saveNow() {
        pendingSave?.cancel()
        pendingSave = nil
        prepareDirectory()
        let entries = entries, file = storeFile
        Self.saveQueue.sync { Self.write(entries, to: file) }
    }

    nonisolated private static func write(_ entries: [ClipEntry], to file: URL) {
        guard let data = try? JSONEncoder().encode(entries), (try? data.write(to: file, options: .atomic)) != nil else { return }
        try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: file.path)
        // An atomic write makes a new file, so it's kept out of backups again each time.
        excludeFromBackup(file)
    }

    nonisolated private static func excludeFromBackup(_ url: URL, _ excluded: Bool = true) {
        var url = url
        var values = URLResourceValues()
        values.isExcludedFromBackup = excluded
        try? url.setResourceValues(values)
    }

    // MARK: Import

    /// Adds copies from another clipboard app, newest first, without repeating what is already saved.
    /// Returns how many were added, and how many the current limits removed again.
    func importClips(_ clips: [ImportedClip]) -> (added: Int, trimmed: Int) {
        var texts = Set(entries.compactMap(\.text))
        var images = Set(entries.compactMap(\.imageFile))
        // Copies with no date go below what is saved now, in the order they came.
        var undated = (entries.map(\.date).min() ?? Date()).addingTimeInterval(-1)
        var added: [ClipEntry] = []
        for clip in clips {
            let date: Date
            if let known = clip.date { date = known } else { date = undated; undated.addTimeInterval(-1) }
            if let text = clip.text {
                guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, text.utf8.count <= Self.maxTextBytes,
                      !(ignoresPasswords && PasswordFilter.looksLikePassword(text)), texts.insert(text).inserted else { continue }
                added.append(ClipEntry(text: text, date: date))
            } else if let data = clip.image, data.count <= Self.maxImageBytes {
                let name = SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined() + ".png"
                guard images.insert(name).inserted else { continue }
                prepareDirectory()
                guard (try? data.write(to: imageURL(name), options: .atomic)) != nil else { continue }
                try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: imageURL(name).path)
                added.append(ClipEntry(imageFile: name, date: date))
            }
        }
        guard !added.isEmpty else { return (0, 0) }
        let before = entries.count + added.count
        entries = (entries + added).sorted { $0.date > $1.date }
        let result = Self.trimmed(entries, maxEntries: maxEntries, maxImages: maxImages)
        result.removed.forEach(removeImage)
        entries = result.kept
        saveNow()
        return (added.count, before - entries.count)
    }

    private func load() {
        guard let data = try? Data(contentsOf: storeFile),
              let saved = try? JSONDecoder().decode([ClipEntry].self, from: data)
        else { return }
        entries = saved
    }

    private func prepareDirectory() {
        let manager = FileManager.default
        let images = directory.appendingPathComponent("clipboard-images", isDirectory: true)
        try? manager.createDirectory(at: images, withIntermediateDirectories: true)
        for folder in [directory, images] {
            try? manager.setAttributes([.posixPermissions: 0o700], ofItemAtPath: folder.path)
        }
        // Only the history's own files stay out of backups. The folder is shared with todos, notes and layouts,
        // which older versions excluded by mistake; that is undone once.
        Self.excludeFromBackup(images)
        undoSharedExclusion()
    }

    private func undoSharedExclusion() {
        guard !defaults.bool(forKey: "clipboard.backupFixed"), FileManager.default.fileExists(atPath: directory.path) else { return }
        if (try? directory.resourceValues(forKeys: [.isExcludedFromBackupKey]))?.isExcludedFromBackup == true {
            Self.excludeFromBackup(directory, false)
        }
        defaults.set(true, forKey: "clipboard.backupFixed")
    }

    /// The copied image as it is on the clipboard. Turning TIFF into PNG is left to the background queue.
    private static func imageData(from board: NSPasteboard) -> (data: Data, isPNG: Bool)? {
        if let png = board.data(forType: .png) { return (png, true) }
        if let tiff = board.data(forType: .tiff) { return (tiff, false) }
        return nil
    }

    nonisolated private static func png(fromTIFF tiff: Data) -> Data? {
        NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:])
    }
}
